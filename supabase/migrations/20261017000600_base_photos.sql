-- Photos of the base recipes: small copies of each recipe's photo from its source page (the site is named
-- under the recipe), in the private bucket under base/<recipe id>.jpg. Every signed-in member reads them;
-- nobody writes there from the app. Made by content/tools/fetch_images.py and build_images.py.
create policy "family media: base recipe photos" on storage.objects for select to authenticated
  using (bucket_id = 'family' and (storage.foldername(name))[1] = 'base');

-- A base recipe may point at its photo in base/; a family recipe still only at its own family folder.
-- The check from 20261017000100 got a generated name (it reads two columns), so it is found by its text.
do $$
declare c text;
begin
  select conname into c from pg_constraint
  where conrelid = 'public.recipes'::regclass and contype = 'c' and pg_get_constraintdef(oid) like '%photo_path%';
  if c is not null then execute format('alter table public.recipes drop constraint %I', c); end if;
end $$;
alter table public.recipes add constraint recipes_photo_path_check check (
  photo_path is null
  or (household_id is null and photo_path like 'base/%')
  or (household_id is not null and photo_path like household_id::text || '/photos/%'));

-- The update moves the recipes' updated_at, so phones reload the base and get the photos.
